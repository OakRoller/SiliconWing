#!/usr/bin/env python3
"""gen_shaders.py <nvidia-modeset tree> <out.cpp>: embed NVKMS's precompiled head-surface shaders the way the Linux build
does (xz -ce -C none, then `ld -r -b binary`), as an assembly blob with the _binary_<name>_shaders_xz_{start,end} symbols
that nvkms expects. macOS ld has no -b binary, so the kext carries this generated file instead."""
import subprocess, sys, os
kms, out = sys.argv[1], sys.argv[2]
names = ["turing", "ampere", "hopper", "blackwell", "gb20x"]
lines = ['/*', ' * NullMoth NVIDIA driver for macOS', ' * Copyright (c) 2026 NullMoth Systems.',
         ' * SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0', ' *',
         ' * GENERATED by build/arm64/gen_shaders.py from src/nvidia-modeset/src/shaders/g_*_shaders. Do not edit.', ' */', '',
         '__asm__(".section __TEXT,__const\\n"']
for n in names:
    src = os.path.join(kms, "src/shaders", f"g_{n}_shaders")
    data = subprocess.run(["xz", "-ce", "-C", "none"], stdin=open(src, "rb"), capture_output=True, check=True).stdout
    lines.append(f'".globl __binary_{n}_shaders_xz_start\\n.p2align 4\\n__binary_{n}_shaders_xz_start:\\n"')
    for i in range(0, len(data), 64):
        lines.append('".byte ' + ",".join(str(b) for b in data[i:i+64]) + '\\n"')
    lines.append(f'".globl __binary_{n}_shaders_xz_end\\n__binary_{n}_shaders_xz_end:\\n"')
    sys.stderr.write(f"{n}: {os.path.getsize(src)} -> {len(data)} bytes xz\n")
lines.append('".byte 0\\n");')
open(out, "w").write("\n".join(lines) + "\n")
