#!/bin/bash
# mkmtltime.sh: regenerate mtlfmt.inc (the plugin's Metal -> VkFormat mapping, from plugin/NVMTLDevice.m) and build
# out/mtltime/libmtltime.dylib from mtltime.m.
set -e
R="$(cd "$(dirname "$0")/../.." && pwd)"; T="$R/tools/arm64-probes"; mkdir -p "$R/out/mtltime"
python3 - "$R/plugin/NVMTLDevice.m" "$T/mtlfmt.inc" <<'PY'
import sys
src = open(sys.argv[1]).read().split('\n')
s = next(i for i, l in enumerate(src) if l.startswith('static int nvmtl_depthfmt(MTLPixelFormat'))
e = next(i for i, l in enumerate(src) if l.startswith('int nvmtl_pixfmt_public('))
body = [l for l in src[s:e] if 'static MTLPixelFormat seen' not in l and 'int dup = 0;' not in l and 'if (!dup)' not in l]
open(sys.argv[2], 'w').write("// generated by tools/arm64-probes/mkmtltime.sh from plugin/NVMTLDevice.m: the plugin's Metal -> VkFormat mapping\n" + '\n'.join(body) + '\n')
PY
xcrun clang -arch arm64 -O2 -dynamiclib -fobjc-arc -Wno-unused-function -I "$R/../vendor/mesa/include" -I "$T" \
    -framework Metal -framework QuartzCore -framework Foundation "$T/mtltime.m" -o "$R/out/mtltime/libmtltime.dylib"
echo "built $R/out/mtltime/libmtltime.dylib"
